// Generate Supabase seed SQL for the read-only reference tables (foods,
// cooked_foods) from the bundled assets/db/ifct2017.db.
//
//   node scripts/gen_supabase_seed.mjs
//
// Output: supabase/seed_foods.sql — run it once in the Supabase SQL editor AFTER
// 0001_init.sql. Uses ON CONFLICT DO NOTHING so it's safe to re-run and never
// overwrites. The N001 kcal source typo is corrected here (CLAUDE.md rule 4) so
// the cloud reference data is canonical.
import fs from 'node:fs';
import initSqlJs from 'sql.js';

const FOODS_COLS = [
  'code', 'name', 'common_name', 'scientific_name', 'group_code', 'food_group',
  'energy_kcal', 'energy_kj', 'protein_g', 'fat_g', 'carb_g', 'fibre_g',
  'water_g', 'ash_g', 'regions', 'qa_note',
];
const COOKED_COLS = [
  'food_code', 'food_name', 'primarysource', 'energy_kcal', 'energy_kj', 'carb_g',
  'protein_g', 'fat_g', 'freesugar_g', 'fibre_g', 'sodium_mg', 'servings_unit',
  'unit_serving_energy_kcal', 'qa_note',
];

function lit(v) {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : 'NULL';
  return `'${String(v).replace(/'/g, "''")}'`;
}

function insertChunk(table, cols, rows) {
  if (rows.length === 0) return '';
  const values = rows
    .map((r) => `  (${cols.map((c, i) => lit(r[i])).join(', ')})`)
    .join(',\n');
  return `INSERT INTO public.${table} (${cols.join(', ')}) VALUES\n${values}\nON CONFLICT DO NOTHING;\n\n`;
}

const SQL = await initSqlJs();
const db = new SQL.Database(fs.readFileSync('assets/db/ifct2017.db'));

let out = '-- Generated by scripts/gen_supabase_seed.mjs — do not edit by hand.\n';
out += '-- Run AFTER supabase/migrations/0001_init.sql.\n\n';

for (const [table, cols] of [['foods', FOODS_COLS], ['cooked_foods', COOKED_COLS]]) {
  const res = db.exec(`SELECT ${cols.join(', ')} FROM ${table}`);
  const rows = res[0].values;
  // Postgres handles large multi-row INSERTs fine; chunk to keep statements sane.
  for (let i = 0; i < rows.length; i += 200) {
    out += insertChunk(table, cols, rows.slice(i, i + 200));
  }
}

// CLAUDE.md rule 4: correct the N001 source typo (~383 -> 191 kcal).
out += "UPDATE public.foods SET energy_kcal = 191.0, energy_kj = 801.0 WHERE code = 'N001';\n";

fs.mkdirSync('supabase', { recursive: true });
fs.writeFileSync('supabase/seed_foods.sql', out);
console.log(`Wrote supabase/seed_foods.sql (${out.length} bytes)`);
